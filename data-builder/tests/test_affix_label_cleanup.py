"""Item enchantment lines whose label the parser used to misread, from the wiki's own markup
(trimmed: icons and links dropped)."""
from bs4 import BeautifulSoup
import pytest

from get_inverted_synonym_map import get_inverted_synonym_map
from parse_affixes_from_cell import (
    convert_affix_text_map_to_affix_map,
    get_fake_bonuses,
    parse_affixes_from_cell,
)


def tip(label, tooltip, inner=''):
    return (f'<span class="popup has_tooltip">{label}'
            f'<span class="popup tooltip"><b>{label}:</b> {tooltip}{inner}</span></span>')


def dice(expression, average):
    return f'<span class="popup has_tooltip">{expression}<span class="popup tooltip">{average}</span></span>'


def item_affixes(li_html):
    cell = BeautifulSoup(f'<td><ul><li>{li_html}</li></ul></td>', 'html.parser').td
    return [
        {key: affix[key] for key in ('name', 'type', 'value') if key in affix}
        for affix in parse_affixes_from_cell('Test Item', cell, get_inverted_synonym_map(), get_fake_bonuses(), 10, {}, {})
    ]


@pytest.mark.parametrize('li_html, expected', [
    # Commentary after the tooltip isn't part of the name
    (tip('Vitality +20', 'Passive: +20 Vitality bonus to Hit Points.') + ' (only from chain end reward)',
     {'name': 'False Life', 'type': 'Vitality', 'value': '20'}),
    (tip('Improved Deception +17', 'This item makes your weapons hard to focus upon and thus provides a +17 '
         'enhancement bonus to Bluff checks.') + ' (<b>Bug: </b> Provides +5 to bluff, not +17)',
     {'name': 'Improved Deception', 'type': 'Enhancement', 'value': '17'}),
    # nor is a wrapper around it
    ('Invisibility (' + tip('Protection +2', 'Passive: +2 Deflection bonus to Armor Class.') + ')',
     {'name': 'Armor Class', 'type': 'Deflection', 'value': '2'}),
    (tip('Diversion 20% (Insight)', 'This item reduces the threat generated by melee damage by 20%.'),
     {'name': 'Diversion', 'type': 'Insight', 'value': '20'}),
    (tip('Exceptional Resistance +2 (Reflex)', 'Passive: +2 bonus to Reflex saves that stacks with all other '
         'bonuses except Exceptional Resistance +2 (Reflex)'),
     {'name': 'Reflex Save', 'type': 'Exceptional', 'value': '2'}),
    (tip('Good Luck - Reflex +1', 'This item gives a +1 Luck bonus to Reflex saves.'),
     {'name': 'Reflex Save', 'type': 'Luck', 'value': '1'}),
    (tip('Inherent Fire Resistance - 25', 'This item provides a +25 Insight bonus to your Fire resistance.'),
     {'name': 'Fire Resistance', 'type': 'Insight', 'value': '25'}),
    (tip('Insightful Positive Autoheal +8 every 10 seconds', 'You regenerate 8 Hit Points using Positive '
         'Energy every 10 seconds. Only the highest value of each Autoheal type applies.'),
     {'name': 'Positive Autoheal', 'type': 'Insight', 'value': '8'}),
])
def test_item_label_is_read_without_its_surroundings(li_html, expected):
    assert item_affixes(li_html) == [expected]


def test_a_qualifier_the_parser_reads_is_not_commentary():
    li_html = tip('Accuracy +3', '+3 Competence bonus to Attack.') + ' (if Quarterstaff)'

    assert item_affixes(li_html)[0]['name'] != 'Accuracy +3 (if Quarterstaff)'
    assert 'Quarterstaff' not in item_affixes(li_html)[0]['name']


def test_damage_dice_inside_a_tooltip_are_part_of_its_effect():
    # The nested dice tooltip made the line look like two effects, and the second
    # pass named it after the rest of the tooltip sentence.
    li_html = tip("Yeenoghu's Butchery", '+18% Enhancement bonus to Doublestrike chance. In addition, on hit '
                  'with this weapon, you deal an extra ', dice('15d6', '15 to 90') + ' Piercing Damage.')

    assert item_affixes(li_html) == [{'name': "Yeenoghu's Butchery", 'type': 'Bool', 'value': 1}]


def test_a_wiki_template_error_is_not_an_affix():
    error = ('<span class="popup has_tooltip"><div class="error">Maximum number of loops have been performed'
             '</div>0d4<span class="popup tooltip">Expression error</span></span>')
    li_html = tip('Solar VI', 'On Hit: ', error + ' Light Damage.')

    assert [affix['name'] for affix in item_affixes(li_html)] == ['Solar']


@pytest.mark.parametrize('label, expected', [
    ('Required Trait: Chaotic (UMD: 20)', 'Required Trait: Chaotic'),
    ('Required Class: Paladin (UMD: 0)', 'Required Class: Paladin'),
    ('Class Required: Wizard, Sorcerer, Bard (UMD: 0)', 'Required Class: Wizard, Sorcerer, Bard'),
])
def test_a_use_requirement_is_a_flag(label, expected):
    assert item_affixes(label) == [{'name': expected, 'type': 'Bool', 'value': 1}]


def test_a_number_inside_an_unclosed_parenthesis_stays_in_the_name():
    assert item_affixes('Glacial Mint Bon Bon (Cone of Cold, CL 10)') == [
        {'name': 'Glacial Mint Bon Bon (Cone of Cold, CL 10)', 'type': 'Bool', 'value': 1},
    ]


def test_a_value_with_no_bonus_type_is_untyped():
    li_html = tip('Corroding 7', 'This effect causes the edges of this weapon to drip with acid, dealing 7d6 '
                  'Acid damage on each critical hit.')

    assert item_affixes(li_html) == [{'name': 'Corroding', 'type': 'Untyped', 'value': '7'}]


@pytest.mark.parametrize('label, words, expected', [
    ('Lesser Arcane Augmentation IX', 'ninth level or lower sorcerer or wizard spells by one', '1'),
    ('Arcane Augmentation I', 'first level sorcerer or wizard spells by two', '2'),
    ('Improved Fire Augmentation IX', 'ninth level or lower Fire spells by three', '3'),
])
def test_an_augmentation_is_worth_its_caster_levels_not_its_spell_level(label, words, expected):
    li_html = tip(label, f"Increases the wearer's caster level when casting {words}.")

    assert item_affixes(li_html)[0]['value'] == expected


def test_a_tooltip_sentence_is_not_taken_for_a_stat_name():
    affix = convert_affix_text_map_to_affix_map({
        'text': 'Thunderbane',
        'tooltip': "Thunderbane: Against constructs and the undead, this weapon's effective enhancement bonus is "
                   '+8 better than its normal enhancement bonus. It deals an extra 7d6 of damage against the foes.',
    })

    assert affix['name'] == 'Thunderbane'


def test_elemental_resistance_takes_the_tooltips_bonus_type_over_its_labels():
    # The label says Competence; the tooltip, and the item's screenshot, say Insight.
    li_html = tip('Competence Elemental Resistance - 10', 'This item provides a +10 Insight bonus to your Acid, '
                  'Cold, Fire, and Electrical resistances.')

    assert item_affixes(li_html) == [{'name': 'Elemental Resistance', 'type': 'Insight', 'value': '10'}]


def test_elemental_resistance_agreeing_with_its_tooltip_is_unchanged():
    li_html = tip('Competence Elemental Resistance - 10', 'This item provides a +10 Competence bonus to your Acid, '
                  'Cold, Fire, and Electrical resistances.')

    assert item_affixes(li_html) == [{'name': 'Elemental Resistance', 'type': 'Competence', 'value': '10'}]
